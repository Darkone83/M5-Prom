int image_timezone_count(void){return (int)(sizeof(zones)/sizeof(zones[0]));}
const char *image_timezone_name(int index){return index>=0&&index<image_timezone_count()?zones[index].name:"CUSTOM";}
static int nibble(char c){return c>='0'&&c<='9'?c-'0':c>='A'&&c<='F'?c-'A'+10:-1;}
static void decode(int index,uint8_t out[44])
{
    const char *p=zones[index].hex;
    for(int j=0;j<44;j++)out[j]=(uint8_t)((nibble(p[j*2])<<4)|nibble(p[j*2+1]));
}
int image_timezone_find(const uint8_t raw44[44])
{
    if(!raw44)return -1;
    uint8_t buf[44];
    for(int i=0;i<image_timezone_count();i++){
        decode(i,buf);
        if(memcmp(raw44,buf,sizeof(buf))==0)return i;
    }
    return -1;
}
bool image_timezone_apply(uint8_t raw44[44],int index)
{
    if(!raw44||index<0||index>=image_timezone_count())return false;
    decode(index,raw44);
    return true;
}
